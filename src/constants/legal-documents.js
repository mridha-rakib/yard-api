const isLegacyAutoGeneratedLegalBody = (documentId = "", value = "") => {
  const normalizedValue = String(value || "").trim();

  if (!normalizedValue) {
    return false;
  }

  if (String(documentId || "").trim() === "terms-of-service") {
    return LEGACY_AUTOGENERATED_TERMS_PATTERNS.every((pattern) => pattern.test(normalizedValue));
  }

  if (String(documentId || "").trim() === "privacy-policy") {
    return LEGACY_AUTOGENERATED_PRIVACY_PATTERNS.every((pattern) => pattern.test(normalizedValue));
  }

  return false;
};

